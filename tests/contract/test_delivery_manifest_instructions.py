"""The manifest's verification steps must work on what the tag actually holds.

**The defect this exists for.** `MANIFEST.md` told a recipient:

    From the root of a checkout of the tag above:
        sha256sum -c docs/delivery/SHA256SUMS
    Every line must read `OK`.

That cannot pass. `.gitignore` excludes `docs/delivery/pdf/`, so the four PDFs
— Works 1, 3 and 4, the artefacts Schedule A actually accepts — are generated
rather than committed, and a clean checkout of the tag reports four
`FAILED open or read` lines. The design is sound and the PDFs are genuinely
byte-reproducible; what was wrong was the document telling the recipient of a
contract delivery to run a command that reports failure, with no warning that
failure is expected.

It survived because the two halves were checked separately and by different
things. `test_delivery_manifest_matches_the_files_it_identifies` verifies the
hashes and deliberately tolerates absent artefacts; nothing read the prose. A
reviewer following the instructions literally would conclude the delivery was
corrupt — and nobody had followed them, because everyone ran the command in a
working tree where the generated PDFs happen to exist.

So: whenever a hashed artefact is not in the repository, the manifest has to
say so.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DELIVERY = ROOT / "docs" / "delivery"


def _hashed_paths() -> list[str]:
    sums = DELIVERY / "SHA256SUMS"
    assert sums.is_file(), "docs/delivery/SHA256SUMS is missing"
    out = []
    for line in sums.read_text().splitlines():
        if line.strip():
            out.append(line.split("  ", 1)[1])
    return out


def _tracked() -> set[str]:
    result = subprocess.run(
        ["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True
    )
    return set(result.stdout.splitlines())


def test_untracked_artefacts_are_declared_in_the_manifest():
    """A hashed file absent from the tag must be called out as generated."""
    untracked = sorted(set(_hashed_paths()) - _tracked())
    manifest = (DELIVERY / "MANIFEST.md").read_text()

    if not untracked:
        return  # Everything hashed is in the tag; no warning needed.

    assert "not in the repository" in manifest, (
        f"{len(untracked)} artefact(s) in SHA256SUMS are not tracked by git "
        f"— {untracked} — so `sha256sum -c` on a checkout of the tag reports "
        "them as FAILED. MANIFEST.md must say so, or a recipient following "
        "its instructions concludes the delivery is corrupt. Regenerate with "
        "`python scripts/delivery_manifest.py --tag <name>`."
    )


def test_the_manifest_offers_a_procedure_that_works_from_a_bare_checkout():
    """Rebuilding is the only check available to someone who has only the tag,
    so it must be named, not merely implied."""
    manifest = (DELIVERY / "MANIFEST.md").read_text()
    assert "render_delivery_pdfs.py" in manifest, (
        "MANIFEST.md does not tell a recipient how to produce the PDFs the "
        "tag does not carry"
    )
    assert "byte-reproducible" in manifest


def test_the_manifest_does_not_promise_an_unqualified_all_ok():
    """The exact wording that was wrong.

    `sha256sum -c` is still the right command and still appears — what must
    not reappear is a bare 'every line must read OK' attached to a plain
    checkout, with no mention that four of them will not.
    """
    manifest = (DELIVERY / "MANIFEST.md").read_text()
    if "Every line must read" not in manifest:
        return
    warning_index = manifest.find("not in the repository")
    claim_index = manifest.find("Every line must read")
    assert 0 <= warning_index < claim_index, (
        "MANIFEST.md claims every line reads OK before explaining that the "
        "PDFs are not in the repository. A recipient reads the claim, runs "
        "the command, sees four failures, and has no way to know that is "
        "expected."
    )


def test_every_hashed_artefact_exists_or_is_generated():
    """An artefact that is neither tracked nor generated by the renderer is
    simply missing, and no wording fixes that."""
    renderer = (ROOT / "scripts" / "render_delivery_pdfs.py").read_text()
    tracked = _tracked()
    for relative in _hashed_paths():
        if relative in tracked:
            continue
        assert relative.startswith("docs/delivery/pdf/"), (
            f"{relative} is hashed in SHA256SUMS, is not in the repository, "
            "and is not a PDF the delivery renderer produces"
        )
        assert Path(relative).stem in renderer or "DELIVERY" in renderer, (
            f"{relative} is hashed but nothing in render_delivery_pdfs.py "
            "appears to produce it"
        )
